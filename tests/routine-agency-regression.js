'use strict';
const assert=require('assert');
require('./mock.js');
const W=require('./ui-gate-sync.js').fresh().WA;
W.store.init();
W.actionDesk.setSettings({enabled:true});
W.injectCollector.setSettings({enabled:true,maxItems:12});
W.life.setSettings({enabled:true});
const R=W.routinePacing;
assert.strictEqual(R.evaluate('未知').ok,false);
R.setWorldPreset('cn_high_school',{slot:'morning_core',dayType:'weekday'});
R.setActorProfile('甲',{disposition:'rebel',willingness:15,backstory:'厌学，但想和朋友一起毕业',context:{consequenceConcern:'怕处分影响毕业',goal:'一起毕业'}});
let e=R.evaluate('甲');
assert.strictEqual(e.pattern,'reluctant_candidate');
assert.strictEqual(e.status,'candidate');
assert(e.detail.includes('一起毕业')&&e.detail.includes('怕处分'));
assert(!e.detail.includes('人早就'));
R.setActorProfile('甲',{backstory:'曾有兼职经历'});
assert.strictEqual(R.listActors()[0].willingness,15);
assert.strictEqual(R.listActors()[0].disposition,'rebel');
R.advanceSlot({slot:'lunch_break'});
e=R.evaluate('甲'); assert.strictEqual(e.pattern,'meal_candidate'); assert(!e.detail.includes('冷馒头'));
R.advanceSlot({slot:'late_sleep'});
assert.strictEqual(R.evaluate('甲').pattern,'recovery_candidate');
R.advanceSlot({slot:'morning_core',dayType:'sunday'});
assert(R.evaluate('甲').detail.includes('周末安排未知'));
R.setActorProfile('乙',{preset:'cultivation_disciple',disposition:'withdrawn',context:{leisurePreference:'在洞府照料灵草',weekendDuty:false}});
e=R.evaluate('乙'); assert(e.detail.includes('洞府')); assert(!/网吧|微信|奶茶/.test(e.detail));
const before=JSON.stringify(W.store.get());
assert.strictEqual(R.buildBlock(),R.buildBlock());
assert.strictEqual(JSON.stringify(W.store.get()),before);
W.store.transact(function(d){d.clock.iso='2026-11-06T12:20:00+08:00';});
assert.strictEqual(R.evaluate('甲').slot,'lunch_break');
assert.strictEqual(R.evaluate('甲').timeSource,'story-iso');
const injected=W.injectCollector.buildBlock({people:['甲']});
assert(injected.includes('行动候选'));
assert(injected.includes('正午'));
console.log('routine agency regression: PASS (identity is not destiny; pure candidates; story clock; genre isolation)');
